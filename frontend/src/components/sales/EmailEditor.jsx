import { useState } from "react";
import {
  Check,
  Eye,
  Mail,
  Pencil,
  RefreshCw,
  Save,
  Send,
  X,
} from "lucide-react";
import { demoMode } from "../../services/demoData.js";

export default function EmailEditor({
  lead,
  draft,
  onChange,
  onGenerate,
  onSave,
  onReject,
  onApproveAndSend,
}) {
  const [preview, setPreview] = useState(false);

  if (!draft) {
    return (
      <div className="rounded-lg border border-dashed border-slate-300 bg-slate-50/60 p-4">
        <div className="flex items-start gap-3">
          <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-lg bg-white text-slate-500">
            <Mail size={16} />
          </span>
          <div className="min-w-0 flex-1">
            <p className="text-xs font-semibold text-slate-700">
              No email draft
            </p>
            <p className="mt-1 text-[11px] leading-5 text-muted">
              Draft generation requires the FastAPI/OpenAI backend.
            </p>
          </div>
        </div>
        <button
          className="mt-3 inline-flex h-8 items-center gap-2 rounded-lg border border-line bg-white px-3 text-[11px] font-semibold text-slate-700 hover:bg-slate-50"
          onClick={() => onGenerate(lead)}
          type="button"
        >
          <Mail size={14} />
          {demoMode ? "Generate demo draft" : "Generate email"}
        </button>
      </div>
    );
  }

  return (
    <div className="overflow-hidden rounded-lg border border-line">
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-line bg-slate-50 px-3 py-2.5">
        <div>
          <p className="text-xs font-semibold text-slate-700">Email draft</p>
          <p className="mt-0.5 text-[10px] text-amber-700">
            {demoMode
              ? "DEMO CONTENT · not generated by AI"
              : "AI draft · review before sending"}
          </p>
        </div>
        <button
          className="inline-flex items-center gap-1.5 rounded-md px-2 py-1 text-[10px] font-medium text-slate-600 hover:bg-white"
          onClick={() => setPreview((value) => !value)}
          type="button"
        >
          {preview ? <Pencil size={13} /> : <Eye size={13} />}
          {preview ? "Edit" : "Preview"}
        </button>
      </div>

      <div className="space-y-3 p-3">
        <div className="border-b border-line pb-2 text-[11px]">
          <span className="text-slate-400">To </span>
          <span className="font-medium text-slate-700">{lead.email}</span>
        </div>
        <label className="block">
          <span className="mb-1 block text-[10px] font-semibold uppercase tracking-wide text-slate-400">
            Subject
          </span>
          {preview ? (
            <p className="text-xs font-medium text-slate-800">
              {draft.subject}
            </p>
          ) : (
            <input
              className="h-9 w-full rounded-md border border-line px-2.5 text-xs text-slate-700 outline-none focus:border-brand-400"
              onChange={(event) =>
                onChange({ ...draft, subject: event.target.value })
              }
              value={draft.subject}
            />
          )}
        </label>
        <label className="block">
          <span className="mb-1 block text-[10px] font-semibold uppercase tracking-wide text-slate-400">
            Message
          </span>
          {preview ? (
            <pre className="whitespace-pre-wrap font-sans text-xs leading-5 text-slate-700">
              {draft.body}
            </pre>
          ) : (
            <textarea
              className="min-h-36 w-full resize-y rounded-md border border-line px-2.5 py-2 text-xs leading-5 text-slate-700 outline-none focus:border-brand-400"
              onChange={(event) =>
                onChange({ ...draft, body: event.target.value })
              }
              value={draft.body}
            />
          )}
        </label>
        <div className="flex flex-wrap gap-2 border-t border-line pt-3">
          <button
            className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-line px-2.5 text-[10px] font-semibold text-slate-700 hover:bg-slate-50"
            onClick={() => onGenerate(lead)}
            type="button"
          >
            <RefreshCw size={13} />
            {demoMode ? "Regenerate demo" : "Regenerate"}
          </button>
          <button
            className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-line px-2.5 text-[10px] font-semibold text-slate-700 hover:bg-slate-50"
            onClick={() => onSave(lead, draft)}
            type="button"
          >
            <Save size={13} />
            Save draft
          </button>
          <button
            className="inline-flex h-8 items-center gap-1.5 rounded-lg border border-rose-200 px-2.5 text-[10px] font-semibold text-rose-700 hover:bg-rose-50"
            onClick={() => onReject(lead)}
            type="button"
          >
            <X size={13} />
            Reject
          </button>
          <button
            className="inline-flex h-8 items-center gap-1.5 rounded-lg bg-brand-600 px-2.5 text-[10px] font-semibold text-white hover:bg-brand-700"
            onClick={() => onApproveAndSend(lead)}
            type="button"
          >
            <Send size={13} />
            Approve &amp; Send
          </button>
        </div>
        <p className="flex items-start gap-1.5 text-[10px] leading-4 text-amber-800">
          <Check className="mt-0.5 shrink-0" size={12} />
          {demoMode
            ? "Sending is disabled in this demo. Live sending requires backend approval and verified recipient eligibility."
            : "Sending requires backend approval and verified recipient eligibility."}
        </p>
      </div>
    </div>
  );
}
